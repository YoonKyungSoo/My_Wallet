--  번호 | 테이블명                  | 설명
-- ------+---------------------------+--------------------------------------------------
--   1   | badges                    | 뱃지 마스터(코드·제목·아이콘 등). users 대표뱃지 FK
--   2   | users                     | 회원 계정(로그인·닉네임·역할·정지·프로필·대표뱃지)
--   3   | restaurants               | 식당 본문(주소·카테고리·평점·메뉴·사진·좌표·삭제여부)
--   4   | restaurant_submissions    | 식당 등록 제보·승인 워크플로(상태·승인 결과 식당 id)
--   5   | map_comments              | 지도/상세 방문 리뷰(댓글·스냅샷·별점·사진)
--   6   | comment_reports           | 댓글 신고(신고자·대상·사유·처리상태)
--   7   | bug_reports               | 버그 제보(식당·설명·사진·상태)
--   8   | bookmarks                 | 사용자 즐겨찾기(user–restaurant)
--   9   | unban_requests            | 정지 해제 요청(대상·처리 관리자·상태)
--  10   | site_notice               | 사이트 공지(본문·노출·수정자)
--  11   | activity_events           | 활동 이벤트 로그(종류·payload·통계·배지 근거)
--  12   | user_badges               | 사용자에게 부여된 뱃지(부여 시각·근거 활동)
--  13   | restaurant_hidden_photos  | 식당 갤러리에서 숨긴 사진 URL
-- =============================================================================
